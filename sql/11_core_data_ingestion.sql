INSERT INTO RTRW_DB.CORE.DIM_DATE

WITH DATE_RANGE AS (

    SELECT
        MIN(ORDER_PURCHASE_TIMESTAMP)::DATE AS START_DATE,
        MAX(ORDER_PURCHASE_TIMESTAMP)::DATE AS END_DATE
    FROM RTRW_DB.STAGING.ORDERS_CLEAN

),

ALL_DATES AS (

    SELECT
        DATEADD(
            DAY,
            SEQ4(),
            START_DATE
        )::DATE AS FULL_DATE

    FROM DATE_RANGE,
    TABLE(GENERATOR(ROWCOUNT => 10000))

    WHERE DATEADD(DAY, SEQ4(), START_DATE) <= END_DATE

)

SELECT
    TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')),

    FULL_DATE,

    DAY(FULL_DATE),

    DAYNAME(FULL_DATE),

    MONTH(FULL_DATE),

    MONTHNAME(FULL_DATE),

    QUARTER(FULL_DATE),

    YEAR(FULL_DATE),

    WEEKOFYEAR(FULL_DATE),

    DAYOFWEEKISO(FULL_DATE) IN (6, 7)

FROM ALL_DATES;

