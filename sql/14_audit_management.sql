INSERT INTO RTRW_DB.AUDIT.RECONCILIATION_SNAPSHOT (
    RUN_ID,
    SNAPSHOT_DATE,
    TOTAL_ORDERS,
    MATCHED_ORDERS,
    UNMATCHED_ORDERS,
    TOTAL_ORDER_VALUE,
    TOTAL_PAYMENT_VALUE,
    TOTAL_REFUND_VALUE,
    TOTAL_VARIANCE
)

SELECT
    (
        SELECT MAX(RUN_ID)
        FROM RTRW_DB.AUDIT.RECONCILIATION_RUN
    ),

    CURRENT_TIMESTAMP(),

    COUNT(*),

    COUNT_IF(
        RECONCILIATION_STATUS = 'MATCHED'
    ),

    COUNT_IF(
        RECONCILIATION_STATUS <> 'MATCHED'
    ),

    SUM(COALESCE(TOTAL_ITEM_VALUE, 0)),

    SUM(COALESCE(TOTAL_PAYMENT_VALUE, 0)),

    SUM(COALESCE(TOTAL_COMPLETED_REFUNDS, 0)),

    SUM(COALESCE(PAYMENT_VARIANCE, 0))

FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS;

SELECT *
FROM RTRW_DB.AUDIT.RECONCILIATION_RUN
ORDER BY RUN_ID DESC;

SELECT *
FROM RTRW_DB.AUDIT.RECONCILIATION_SNAPSHOT
ORDER BY SNAPSHOT_DATE DESC;

SELECT *
FROM RTRW_DB.AUDIT.EXCEPTION_HISTORY
ORDER BY UPDATED_AT DESC;