WITH PAYMENT_TOTALS AS (

    SELECT
        ORDER_ID,
        SUM(TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2))
            AS PAYMENT_AMOUNT
    FROM RTRW_DB.RAW.RAW_PAYMENTS
    GROUP BY ORDER_ID

),

REFUND_TOTALS AS (

    SELECT
        ORDER_ID,
        SUM(TRY_TO_DECIMAL(REFUND_AMOUNT, 18, 2))
            AS REFUND_AMOUNT
    FROM RTRW_DB.RAW.RAW_REFUNDS
    WHERE UPPER(TRIM(REFUND_STATUS)) = 'COMPLETED'
    GROUP BY ORDER_ID

)

SELECT
    R.ORDER_ID,
    R.REFUND_AMOUNT,
    P.PAYMENT_AMOUNT

FROM REFUND_TOTALS R

JOIN PAYMENT_TOTALS P
    ON R.ORDER_ID = P.ORDER_ID

WHERE R.REFUND_AMOUNT > P.PAYMENT_AMOUNT;