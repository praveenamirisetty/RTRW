SELECT
    ORDER_ID,

    SUM(
        TRY_TO_DECIMAL(PRICE, 18, 2)
    ) AS PRODUCT_VALUE,

    SUM(
        TRY_TO_DECIMAL(FREIGHT_VALUE, 18, 2)
    ) AS FREIGHT_VALUE,

    SUM(
        TRY_TO_DECIMAL(PRICE, 18, 2) +
        TRY_TO_DECIMAL(FREIGHT_VALUE, 18, 2)
    ) AS TOTAL_ITEM_VALUE

FROM RTRW_DB.RAW.RAW_ORDER_ITEMS

GROUP BY ORDER_ID;

SELECT
    ORDER_ID,

    SUM(
        TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2)
    ) AS TOTAL_PAYMENT

FROM RTRW_DB.RAW.RAW_PAYMENTS

GROUP BY ORDER_ID;

WITH ITEM_TOTALS AS (

    SELECT
        ORDER_ID,

        SUM(
            TRY_TO_DECIMAL(PRICE, 18, 2) +
            TRY_TO_DECIMAL(FREIGHT_VALUE, 18, 2)
        ) AS ITEM_TOTAL

    FROM RTRW_DB.RAW.RAW_ORDER_ITEMS
    GROUP BY ORDER_ID

),

PAYMENT_TOTALS AS (

    SELECT
        ORDER_ID,

        SUM(
            TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2)
        ) AS PAYMENT_TOTAL

    FROM RTRW_DB.RAW.RAW_PAYMENTS
    GROUP BY ORDER_ID

)

SELECT
    O.ORDER_ID,

    I.ITEM_TOTAL,

    P.PAYMENT_TOTAL,

    ROUND(
        I.ITEM_TOTAL - P.PAYMENT_TOTAL,
        2
    ) AS FINANCIAL_VARIANCE

FROM RTRW_DB.RAW.RAW_ORDERS O

LEFT JOIN ITEM_TOTALS I
    ON O.ORDER_ID = I.ORDER_ID

LEFT JOIN PAYMENT_TOTALS P
    ON O.ORDER_ID = P.ORDER_ID

ORDER BY ABS(
    COALESCE(I.ITEM_TOTAL, 0) -
    COALESCE(P.PAYMENT_TOTAL, 0)
) DESC;

