INSERT INTO RTRW_DB.CORE.EXCEPTION_QUEUE (
    ORDER_ID,
    EXCEPTION_TYPE,
    ORDER_AMOUNT,
    PAYMENT_AMOUNT,
    REFUND_AMOUNT,
    VARIANCE_AMOUNT,
    EXCEPTION_STATUS,
    PRIORITY
)

SELECT
    ORDER_ID,

    RECONCILIATION_STATUS,

    TOTAL_ITEM_VALUE,

    TOTAL_PAYMENT_VALUE,

    TOTAL_COMPLETED_REFUNDS,

    PAYMENT_VARIANCE,

    'OPEN',

    CASE
        WHEN ABS(PAYMENT_VARIANCE) > 1000
            THEN 'HIGH'

        WHEN ABS(PAYMENT_VARIANCE) > 100
            THEN 'MEDIUM'

        ELSE 'LOW'
    END

FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS

WHERE RECONCILIATION_STATUS <> 'MATCHED';

SELECT
    EXCEPTION_ID,
    ORDER_ID,
    EXCEPTION_TYPE,
    VARIANCE_AMOUNT,
    EXCEPTION_STATUS,
    PRIORITY,
    CREATED_AT

FROM RTRW_DB.CORE.EXCEPTION_QUEUE

ORDER BY
    CASE PRIORITY
        WHEN 'HIGH' THEN 1
        WHEN 'MEDIUM' THEN 2
        ELSE 3
    END,

    CREATED_AT DESC;

SELECT
    EXCEPTION_ID,

    ORDER_ID,

    EXCEPTION_TYPE,

    EXCEPTION_STATUS,

    DATEDIFF(
        DAY,
        CREATED_AT,
        COALESCE(RESOLVED_AT, CURRENT_TIMESTAMP())
    ) AS AGING_DAYS

FROM RTRW_DB.CORE.EXCEPTION_QUEUE;

UPDATE RTRW_DB.CORE.EXCEPTION_QUEUE

SET
    EXCEPTION_STATUS = 'RESOLVED',
    RESOLVED_AT = CURRENT_TIMESTAMP()

WHERE EXCEPTION_ID = 1
  AND EXCEPTION_STATUS = 'OPEN';

INSERT INTO RTRW_DB.AUDIT.EXCEPTION_HISTORY (
    EXCEPTION_ID,
    ORDER_ID,
    OLD_STATUS,
    NEW_STATUS,
    ACTION_DESCRIPTION,
    UPDATED_BY
)

SELECT
    EXCEPTION_ID,
    ORDER_ID,
    'OPEN',
    'RESOLVED',
    'Exception resolved after investigation',
    CURRENT_USER()

FROM RTRW_DB.CORE.EXCEPTION_QUEUE

WHERE EXCEPTION_ID = 1
  AND EXCEPTION_STATUS = 'RESOLVED';