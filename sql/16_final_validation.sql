SELECT COUNT(*) AS INVALID_CUSTOMERS

FROM RTRW_DB.CORE.FACT_ORDER O

LEFT JOIN RTRW_DB.CORE.DIM_CUSTOMER C

    ON O.CUSTOMER_ID = C.CUSTOMER_ID

WHERE C.CUSTOMER_ID IS NULL;

SELECT COUNT(*) AS INVALID_PRODUCTS

FROM RTRW_DB.CORE.FACT_ORDER_ITEM I

LEFT JOIN RTRW_DB.CORE.DIM_PRODUCT P

    ON I.PRODUCT_ID = P.PRODUCT_ID

WHERE P.PRODUCT_ID IS NULL;

SELECT COUNT(*) AS INVALID_SELLERS

FROM RTRW_DB.CORE.FACT_ORDER_ITEM I

LEFT JOIN RTRW_DB.CORE.DIM_SELLER S

    ON I.SELLER_ID = S.SELLER_ID

WHERE S.SELLER_ID IS NULL;

SELECT COUNT(*) AS INVALID_REFUND_ORDERS

FROM RTRW_DB.CORE.FACT_REFUND R

LEFT JOIN RTRW_DB.CORE.FACT_ORDER O

    ON R.ORDER_ID = O.ORDER_ID

WHERE O.ORDER_ID IS NULL;

SELECT
    DATA_ORIGIN,
    COUNT(*) AS TOTAL_RECORDS

FROM RTRW_DB.CORE.FACT_REFUND

GROUP BY DATA_ORIGIN;

SELECT
    RECONCILIATION_STATUS,
    COUNT(*) AS TOTAL_ORDERS

FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS

GROUP BY RECONCILIATION_STATUS

ORDER BY TOTAL_ORDERS DESC;

SELECT
    EXCEPTION_STATUS,
    PRIORITY,
    COUNT(*) AS TOTAL_EXCEPTIONS

FROM RTRW_DB.CORE.EXCEPTION_QUEUE

GROUP BY
    EXCEPTION_STATUS,
    PRIORITY;