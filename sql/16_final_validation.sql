SELECT 'RAW_CUSTOMERS', COUNT(*)
FROM RTRW_DB.RAW.RAW_CUSTOMERS

UNION ALL

SELECT 'RAW_SELLERS', COUNT(*)
FROM RTRW_DB.RAW.RAW_SELLERS

UNION ALL

SELECT 'RAW_PRODUCTS', COUNT(*)
FROM RTRW_DB.RAW.RAW_PRODUCTS

UNION ALL

SELECT 'RAW_REFUNDS', COUNT(*)
