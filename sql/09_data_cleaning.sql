CREATE OR REPLACE TABLE RTRW_DB.STAGING.ORDERS_CLEAN AS

SELECT
    TRIM(ORDER_ID) AS ORDER_ID,

    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,

    UPPER(TRIM(ORDER_STATUS)) AS ORDER_STATUS,

    TRY_TO_TIMESTAMP_NTZ(
        NULLIF(TRIM(ORDER_PURCHASE_TIMESTAMP), '')
    ) AS ORDER_PURCHASE_TIMESTAMP,

    TRY_TO_TIMESTAMP_NTZ(
        NULLIF(TRIM(ORDER_APPROVED_AT), '')
    ) AS ORDER_APPROVED_AT,

    TRY_TO_TIMESTAMP_NTZ(
        NULLIF(TRIM(ORDER_DELIVERED_CARRIER_DATE), '')
    ) AS ORDER_DELIVERED_CARRIER_DATE,

    TRY_TO_TIMESTAMP_NTZ(
        NULLIF(TRIM(ORDER_DELIVERED_CUSTOMER_DATE), '')
    ) AS ORDER_DELIVERED_CUSTOMER_DATE,

    TRY_TO_TIMESTAMP_NTZ(
        NULLIF(TRIM(ORDER_ESTIMATED_DELIVERY_DATE), '')
    ) AS ORDER_ESTIMATED_DELIVERY_DATE

FROM RTRW_DB.RAW.RAW_ORDERS

WHERE ORDER_ID IS NOT NULL
  AND TRIM(ORDER_ID) <> '';

  CREATE OR REPLACE TABLE RTRW_DB.STAGING.PAYMENTS_CLEAN AS

SELECT
    TRIM(ORDER_ID) AS ORDER_ID,

    TRY_TO_NUMBER(PAYMENT_SEQUENTIAL) AS PAYMENT_SEQUENTIAL,

    UPPER(TRIM(PAYMENT_TYPE)) AS PAYMENT_TYPE,

    TRY_TO_NUMBER(PAYMENT_INSTALLMENTS) AS PAYMENT_INSTALLMENTS,

    TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2) AS PAYMENT_VALUE

FROM RTRW_DB.RAW.RAW_PAYMENTS

WHERE ORDER_ID IS NOT NULL
  AND TRIM(ORDER_ID) <> '';

CREATE OR REPLACE TABLE RTRW_DB.STAGING.ORDER_ITEMS_CLEAN AS

SELECT
    TRIM(ORDER_ID) AS ORDER_ID,

    TRY_TO_NUMBER(ORDER_ITEM_ID) AS ORDER_ITEM_ID,

    TRIM(PRODUCT_ID) AS PRODUCT_ID,

    TRIM(SELLER_ID) AS SELLER_ID,

    TRY_TO_TIMESTAMP_NTZ(
        SHIPPING_LIMIT_DATE
    ) AS SHIPPING_LIMIT_DATE,

    TRY_TO_DECIMAL(PRICE, 18, 2) AS PRICE,

    TRY_TO_DECIMAL(FREIGHT_VALUE, 18, 2) AS FREIGHT_VALUE

FROM RTRW_DB.RAW.RAW_ORDER_ITEMS

WHERE ORDER_ID IS NOT NULL
  AND TRIM(ORDER_ID) <> '';

CREATE OR REPLACE TABLE RTRW_DB.STAGING.CUSTOMERS_CLEAN AS

SELECT
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,

    TRIM(CUSTOMER_UNIQUE_ID) AS CUSTOMER_UNIQUE_ID,

    TRIM(CUSTOMER_ZIP_CODE_PREFIX) AS CUSTOMER_ZIP_CODE_PREFIX,

    INITCAP(TRIM(CUSTOMER_CITY)) AS CUSTOMER_CITY,

    UPPER(TRIM(CUSTOMER_STATE)) AS CUSTOMER_STATE

FROM RTRW_DB.RAW.RAW_CUSTOMERS

WHERE CUSTOMER_ID IS NOT NULL
  AND TRIM(CUSTOMER_ID) <> '';

CREATE OR REPLACE TABLE RTRW_DB.STAGING.SELLERS_CLEAN AS

SELECT
    TRIM(SELLER_ID) AS SELLER_ID,

    TRIM(SELLER_ZIP_CODE_PREFIX) AS SELLER_ZIP_CODE_PREFIX,

    INITCAP(TRIM(SELLER_CITY)) AS SELLER_CITY,

    UPPER(TRIM(SELLER_STATE)) AS SELLER_STATE

FROM RTRW_DB.RAW.RAW_SELLERS

WHERE SELLER_ID IS NOT NULL
  AND TRIM(SELLER_ID) <> '';

CREATE OR REPLACE TABLE RTRW_DB.STAGING.PRODUCTS_CLEAN AS

SELECT
    TRIM(PRODUCT_ID) AS PRODUCT_ID,

    NULLIF(
        TRIM(PRODUCT_CATEGORY_NAME), ''
    ) AS PRODUCT_CATEGORY_NAME,

    TRY_TO_NUMBER(PRODUCT_NAME_LENGHT)
        AS PRODUCT_NAME_LENGTH,

    TRY_TO_NUMBER(PRODUCT_DESCRIPTION_LENGHT)
        AS PRODUCT_DESCRIPTION_LENGTH,

    TRY_TO_NUMBER(PRODUCT_PHOTOS_QTY)
        AS PRODUCT_PHOTOS_QTY,

    TRY_TO_NUMBER(PRODUCT_WEIGHT_G)
        AS PRODUCT_WEIGHT_G,

    TRY_TO_NUMBER(PRODUCT_LENGTH_CM)
        AS PRODUCT_LENGTH_CM,

    TRY_TO_NUMBER(PRODUCT_HEIGHT_CM)
        AS PRODUCT_HEIGHT_CM,

    TRY_TO_NUMBER(PRODUCT_WIDTH_CM)
        AS PRODUCT_WIDTH_CM

FROM RTRW_DB.RAW.RAW_PRODUCTS

WHERE PRODUCT_ID IS NOT NULL
  AND TRIM(PRODUCT_ID) <> '';

CREATE OR REPLACE TABLE RTRW_DB.STAGING.REFUNDS_CLEAN AS

SELECT
    TRIM(REFUND_ID) AS REFUND_ID,

    TRIM(ORDER_ID) AS ORDER_ID,

    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,

    TRY_TO_TIMESTAMP_NTZ(
        REFUND_DATE
    ) AS REFUND_DATE,

    TRY_TO_DECIMAL(
        REFUND_AMOUNT, 18, 2
    ) AS REFUND_AMOUNT,

    TRY_TO_DECIMAL(
        RESTOCKING_FEE, 18, 2
    ) AS RESTOCKING_FEE,

    TRY_TO_DECIMAL(
        TAX_REFUNDED, 18, 2
    ) AS TAX_REFUNDED,

    UPPER(TRIM(REFUND_STATUS)) AS REFUND_STATUS,

    UPPER(TRIM(REFUND_TYPE)) AS REFUND_TYPE,

    UPPER(TRIM(CURRENCY)) AS CURRENCY,

    UPPER(TRIM(DATA_ORIGIN)) AS DATA_ORIGIN

FROM RTRW_DB.RAW.RAW_REFUNDS

WHERE REFUND_ID IS NOT NULL
  AND TRIM(REFUND_ID) <> ''
  AND UPPER(TRIM(DATA_ORIGIN)) = 'SYNTHETIC';

SELECT 'ORDERS_CLEAN' AS TABLE_NAME, COUNT(*) AS TOTAL_ROWS
FROM RTRW_DB.STAGING.ORDERS_CLEAN

UNION ALL

SELECT 'PAYMENTS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.PAYMENTS_CLEAN

UNION ALL

SELECT 'ORDER_ITEMS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.ORDER_ITEMS_CLEAN

UNION ALL

SELECT 'CUSTOMERS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.CUSTOMERS_CLEAN

UNION ALL

SELECT 'SELLERS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.SELLERS_CLEAN

UNION ALL

SELECT 'PRODUCTS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.PRODUCTS_CLEAN

UNION ALL

SELECT 'REFUNDS_CLEAN', COUNT(*)
FROM RTRW_DB.STAGING.REFUNDS_CLEAN;

SELECT
    COUNT(*) AS INVALID_PURCHASE_DATES
FROM RTRW_DB.RAW.RAW_ORDERS R

JOIN RTRW_DB.STAGING.ORDERS_CLEAN C
    ON R.ORDER_ID = C.ORDER_ID

WHERE R.ORDER_PURCHASE_TIMESTAMP IS NOT NULL
  AND TRIM(R.ORDER_PURCHASE_TIMESTAMP) <> ''
  AND C.ORDER_PURCHASE_TIMESTAMP IS NULL;

SELECT
    COUNT(*) AS INVALID_PAYMENT_VALUES
FROM RTRW_DB.RAW.RAW_PAYMENTS

WHERE PAYMENT_VALUE IS NOT NULL
  AND TRIM(PAYMENT_VALUE) <> ''
  AND TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2) IS NULL;

SELECT
    COUNT(*) AS INVALID_ITEM_PRICES
FROM RTRW_DB.RAW.RAW_ORDER_ITEMS

WHERE PRICE IS NOT NULL
  AND TRIM(PRICE) <> ''
  AND TRY_TO_DECIMAL(PRICE, 18, 2) IS NULL;

SELECT
    COUNT(*) AS INVALID_REFUND_AMOUNTS
FROM RTRW_DB.RAW.RAW_REFUNDS

WHERE REFUND_AMOUNT IS NOT NULL
  AND TRIM(REFUND_AMOUNT) <> ''
  AND TRY_TO_DECIMAL(REFUND_AMOUNT, 18, 2) IS NULL;

SELECT
    ORDER_ID,
    COUNT(*) AS RECORD_COUNT
FROM RTRW_DB.STAGING.ORDERS_CLEAN
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;

CREATE TABLE IF NOT EXISTS RTRW_DB.AUDIT.DATA_QUALITY_RESULTS (
    CHECK_ID NUMBER AUTOINCREMENT,
    DATASET_NAME VARCHAR(100),
    CHECK_NAME VARCHAR(200),
    ISSUE_COUNT NUMBER,
    CHECK_STATUS VARCHAR(30),
    CHECKED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO RTRW_DB.AUDIT.DATA_QUALITY_RESULTS
    (DATASET_NAME, CHECK_NAME, ISSUE_COUNT, CHECK_STATUS)

SELECT
    'ORDERS',
    'MISSING_ORDER_ID',
    COUNT_IF(ORDER_ID IS NULL OR TRIM(ORDER_ID) = ''),
    CASE
        WHEN COUNT_IF(ORDER_ID IS NULL OR TRIM(ORDER_ID) = '') = 0
        THEN 'PASS'
        ELSE 'FAIL'
    END
FROM RTRW_DB.RAW.RAW_ORDERS

UNION ALL

SELECT
    'PAYMENTS',
    'INVALID_PAYMENT_AMOUNT',
    COUNT_IF(
        PAYMENT_VALUE IS NOT NULL
        AND TRIM(PAYMENT_VALUE) <> ''
        AND TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2) IS NULL
    ),
    CASE
        WHEN COUNT_IF(
            PAYMENT_VALUE IS NOT NULL
            AND TRIM(PAYMENT_VALUE) <> ''
            AND TRY_TO_DECIMAL(PAYMENT_VALUE, 18, 2) IS NULL
        ) = 0
        THEN 'PASS'
        ELSE 'FAIL'
    END
FROM RTRW_DB.RAW.RAW_PAYMENTS

UNION ALL

SELECT
    'REFUNDS',
    'NON_SYNTHETIC_ORIGIN',
    COUNT_IF(
        UPPER(TRIM(DATA_ORIGIN)) <> 'SYNTHETIC'
        OR DATA_ORIGIN IS NULL
    ),
    CASE
        WHEN COUNT_IF(
            UPPER(TRIM(DATA_ORIGIN)) <> 'SYNTHETIC'
            OR DATA_ORIGIN IS NULL
        ) = 0
        THEN 'PASS'
        ELSE 'FAIL'
    END
FROM RTRW_DB.RAW.RAW_REFUNDS;

SELECT *
FROM RTRW_DB.AUDIT.DATA_QUALITY_RESULTS
ORDER BY CHECKED_AT DESC;