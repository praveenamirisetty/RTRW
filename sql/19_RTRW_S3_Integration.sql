SELECT
    'RAW_ORDERS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_KEY_ROWS,
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID
            FROM RAW.RAW_ORDERS
            GROUP BY ORDER_ID
            HAVING COUNT(*) > 1
        )
    ) AS DUPLICATE_KEY_GROUPS
FROM RAW.RAW_ORDERS

UNION ALL

SELECT
    'RAW_PAYMENTS',
    COUNT(*),
    COUNT_IF(ORDER_ID IS NULL OR PAYMENT_SEQUENTIAL IS NULL),
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID, PAYMENT_SEQUENTIAL
            FROM RAW.RAW_PAYMENTS
            GROUP BY ORDER_ID, PAYMENT_SEQUENTIAL
            HAVING COUNT(*) > 1
        )
    )
FROM RAW.RAW_PAYMENTS

UNION ALL

SELECT
    'RAW_ORDER_ITEMS',
    COUNT(*),
    COUNT_IF(ORDER_ID IS NULL OR ORDER_ITEM_ID IS NULL),
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID, ORDER_ITEM_ID
            FROM RAW.RAW_ORDER_ITEMS
            GROUP BY ORDER_ID, ORDER_ITEM_ID
            HAVING COUNT(*) > 1
        )
    )
FROM RAW.RAW_ORDER_ITEMS

UNION ALL

SELECT
    'RAW_CUSTOMERS',
    COUNT(*),
    COUNT_IF(CUSTOMER_ID IS NULL),
    (
        SELECT COUNT(*)
        FROM (
            SELECT CUSTOMER_ID
            FROM RAW.RAW_CUSTOMERS
            GROUP BY CUSTOMER_ID
            HAVING COUNT(*) > 1
        )
    )
FROM RAW.RAW_CUSTOMERS

UNION ALL

SELECT
    'RAW_SELLERS',
    COUNT(*),
    COUNT_IF(SELLER_ID IS NULL),
    (
        SELECT COUNT(*)
        FROM (
            SELECT SELLER_ID
            FROM RAW.RAW_SELLERS
            GROUP BY SELLER_ID
            HAVING COUNT(*) > 1
        )
    )
FROM RAW.RAW_SELLERS

UNION ALL

SELECT
    'RAW_PRODUCTS',
    COUNT(*),
    COUNT_IF(PRODUCT_ID IS NULL),
    (
        SELECT COUNT(*)
        FROM (
            SELECT PRODUCT_ID
            FROM RAW.RAW_PRODUCTS
            GROUP BY PRODUCT_ID
            HAVING COUNT(*) > 1
        )
    )
FROM RAW.RAW_PRODUCTS

