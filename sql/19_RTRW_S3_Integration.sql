COMPLETE_ORDER_COMPARISON AS (
    SELECT
        O.ORDER_ID,
        O.ORDER_STATUS,
        I.ORDER_VALUE,
        P.PAYMENT_VALUE,

        CASE
            WHEN I.ORDER_ID IS NULL
                THEN 'MISSING_ORDER_ITEMS'

            WHEN P.ORDER_ID IS NULL
                THEN 'MISSING_PAYMENT'

            WHEN ABS(I.ORDER_VALUE - P.PAYMENT_VALUE) <= 0.01
                THEN 'MATCHED'

            WHEN I.ORDER_VALUE > P.PAYMENT_VALUE
                THEN 'UNDERPAID'

            ELSE 'OVERPAID'
        END AS RECONCILIATION_STATUS

    FROM RTRW_DB.RAW.RAW_ORDERS O

    LEFT JOIN ORDER_TOTALS I
        ON O.ORDER_ID = I.ORDER_ID

    LEFT JOIN PAYMENT_TOTALS P
        ON O.ORDER_ID = P.ORDER_ID
)

SELECT
    RECONCILIATION_STATUS,
    COUNT(*) AS ORDER_COUNT,
    SUM(COALESCE(ORDER_VALUE, 0)) AS TOTAL_ORDER_VALUE,
    SUM(COALESCE(PAYMENT_VALUE, 0)) AS TOTAL_PAYMENT_VALUE
FROM COMPLETE_ORDER_COMPARISON
GROUP BY RECONCILIATION_STATUS
ORDER BY RECONCILIATION_STATUS;