SELECT
    T.ORDER_ID AS S3_ORDER_ID,
    R.ORDER_ID AS RAW_ORDER_ID,

    T.CUSTOMER_ID AS S3_CUSTOMER_ID,
    R.CUSTOMER_ID AS RAW_CUSTOMER_ID,

    T.ORDER_STATUS AS S3_STATUS,
    R.ORDER_STATUS AS RAW_STATUS,

    T.ORDER_PURCHASE_TIMESTAMP AS S3_PURCHASE_TIME,
    R.ORDER_PURCHASE_TIMESTAMP AS RAW_PURCHASE_TIME,

    T.ORDER_APPROVED_AT AS S3_APPROVED_AT,
    R.ORDER_APPROVED_AT AS RAW_APPROVED_AT

FROM RTRW_DB.S3_EXT.RTRW_S3_ORDERS_TEST T

JOIN RTRW_DB.RAW.RAW_ORDERS R
    ON T.ORDER_ID = R.ORDER_ID

LIMIT 10;

SELECT
    COUNT(*) AS TOTAL_MATCHED_ORDERS,

    COUNT_IF(
        T.CUSTOMER_ID IS DISTINCT FROM R.CUSTOMER_ID
    ) AS CUSTOMER_ID_DIFF,

    COUNT_IF(
        T.ORDER_STATUS IS DISTINCT FROM R.ORDER_STATUS
    ) AS ORDER_STATUS_DIFF,

    COUNT_IF(
        T.ORDER_PURCHASE_TIMESTAMP IS DISTINCT FROM R.ORDER_PURCHASE_TIMESTAMP
    ) AS PURCHASE_TIMESTAMP_DIFF,

    COUNT_IF(
        T.ORDER_APPROVED_AT IS DISTINCT FROM R.ORDER_APPROVED_AT
    ) AS APPROVED_AT_DIFF,

    COUNT_IF(
        T.ORDER_DELIVERED_CARRIER_DATE IS DISTINCT FROM R.ORDER_DELIVERED_CARRIER_DATE
    ) AS CARRIER_DATE_DIFF,

    COUNT_IF(
        T.ORDER_DELIVERED_CUSTOMER_DATE IS DISTINCT FROM R.ORDER_DELIVERED_CUSTOMER_DATE
    ) AS CUSTOMER_DELIVERY_DATE_DIFF,

    COUNT_IF(
        T.ORDER_ESTIMATED_DELIVERY_DATE IS DISTINCT FROM R.ORDER_ESTIMATED_DELIVERY_DATE
    ) AS ESTIMATED_DELIVERY_DATE_DIFF

FROM RTRW_DB.S3_EXT.RTRW_S3_ORDERS_TEST T
JOIN RTRW_DB.RAW.RAW_ORDERS R
    ON T.ORDER_ID = R.ORDER_ID;

SELECT
    T.ORDER_ID,

    T.ORDER_ESTIMATED_DELIVERY_DATE AS S3_ESTIMATED_DATE,

    R.ORDER_ESTIMATED_DELIVERY_DATE AS RAW_ESTIMATED_DATE,

    TRY_TO_DATE(
        T.ORDER_ESTIMATED_DELIVERY_DATE
    ) AS S3_PARSED_DATE,

    TRY_TO_DATE(
        R.ORDER_ESTIMATED_DELIVERY_DATE
    ) AS RAW_PARSED_DATE

FROM RTRW_DB.S3_EXT.RTRW_S3_ORDERS_TEST T

JOIN RTRW_DB.RAW.RAW_ORDERS R
    ON T.ORDER_ID = R.ORDER_ID

LIMIT 10;

SELECT
    COUNT(*) AS TOTAL_MATCHED_ORDERS,

    COUNT_IF(
        T.CUSTOMER_ID IS DISTINCT FROM R.CUSTOMER_ID
    ) AS CUSTOMER_ID_DIFF,

    COUNT_IF(
        T.ORDER_STATUS IS DISTINCT FROM R.ORDER_STATUS
    ) AS ORDER_STATUS_DIFF,

    COUNT_IF(
        T.ORDER_PURCHASE_TIMESTAMP IS DISTINCT FROM R.ORDER_PURCHASE_TIMESTAMP
    ) AS PURCHASE_TIMESTAMP_DIFF,

    COUNT_IF(
        T.ORDER_APPROVED_AT IS DISTINCT FROM R.ORDER_APPROVED_AT
    ) AS APPROVED_AT_DIFF,

    COUNT_IF(
        T.ORDER_DELIVERED_CARRIER_DATE IS DISTINCT FROM R.ORDER_DELIVERED_CARRIER_DATE
    ) AS CARRIER_DATE_DIFF,

    COUNT_IF(
        T.ORDER_DELIVERED_CUSTOMER_DATE IS DISTINCT FROM R.ORDER_DELIVERED_CUSTOMER_DATE
    ) AS CUSTOMER_DELIVERY_DATE_DIFF,

    COUNT_IF(
        TRY_TO_DATE(T.ORDER_ESTIMATED_DELIVERY_DATE)
        IS DISTINCT FROM
        TRY_TO_DATE(R.ORDER_ESTIMATED_DELIVERY_DATE)
    ) AS ESTIMATED_DELIVERY_DATE_DIFF

FROM RTRW_DB.S3_EXT.RTRW_S3_ORDERS_TEST T

JOIN RTRW_DB.RAW.RAW_ORDERS R
    ON T.ORDER_ID = R.ORDER_ID;

SELECT
    COUNT(*) AS MATCHED_PAYMENT_ROWS,

    COUNT_IF(
        T.PAYMENT_TYPE IS DISTINCT FROM R.PAYMENT_TYPE
    ) AS PAYMENT_TYPE_DIFF,

    COUNT_IF(
        T.PAYMENT_INSTALLMENTS IS DISTINCT FROM R.PAYMENT_INSTALLMENTS
    ) AS INSTALLMENTS_DIFF,

    COUNT_IF(
        T.PAYMENT_VALUE IS DISTINCT FROM R.PAYMENT_VALUE
    ) AS PAYMENT_VALUE_DIFF

FROM RTRW_DB.S3_EXT.RTRW_S3_PAYMENTS_TEST T

JOIN RTRW_DB.RAW.RAW_PAYMENTS R
    ON T.ORDER_ID = R.ORDER_ID
    AND T.PAYMENT_SEQUENTIAL = R.PAYMENT_SEQUENTIAL;

SELECT
    T.ORDER_ID,
    T.PAYMENT_SEQUENTIAL,

    T.PAYMENT_VALUE AS S3_PAYMENT_VALUE,
    R.PAYMENT_VALUE AS RAW_PAYMENT_VALUE,

    TRY_TO_DECIMAL(T.PAYMENT_VALUE, 18, 2)
        AS S3_NUMERIC_VALUE,

    TRY_TO_DECIMAL(R.PAYMENT_VALUE, 18, 2)
        AS RAW_NUMERIC_VALUE,

    TRY_TO_DECIMAL(T.PAYMENT_VALUE, 18, 2)
      - TRY_TO_DECIMAL(R.PAYMENT_VALUE, 18, 2)
        AS VALUE_DIFFERENCE

FROM RTRW_DB.S3_EXT.RTRW_S3_PAYMENTS_TEST T

JOIN RTRW_DB.RAW.RAW_PAYMENTS R
    ON T.ORDER_ID = R.ORDER_ID
    AND T.PAYMENT_SEQUENTIAL = R.PAYMENT_SEQUENTIAL

WHERE
    TRY_TO_DECIMAL(T.PAYMENT_VALUE, 18, 2)
    IS DISTINCT FROM
    TRY_TO_DECIMAL(R.PAYMENT_VALUE, 18, 2)

LIMIT 20;

SELECT
    COUNT(*) AS MATCHED_ROWS,

    COUNT_IF(
        T.ORDER_ID IS DISTINCT FROM R.ORDER_ID
    ) AS ORDER_ID_DIFF,

    COUNT_IF(
        T.ORDER_ITEM_ID IS DISTINCT FROM R.ORDER_ITEM_ID
    ) AS ORDER_ITEM_ID_DIFF,

    COUNT_IF(
        T.PRODUCT_ID IS DISTINCT FROM R.PRODUCT_ID
    ) AS PRODUCT_ID_DIFF,

    COUNT_IF(
        T.SELLER_ID IS DISTINCT FROM R.SELLER_ID
    ) AS SELLER_ID_DIFF,

    COUNT_IF(
        TRY_TO_TIMESTAMP_NTZ(T.SHIPPING_LIMIT_DATE)
        IS DISTINCT FROM
        TRY_TO_TIMESTAMP_NTZ(R.SHIPPING_LIMIT_DATE)
    ) AS SHIPPING_DATE_DIFF,

    COUNT_IF(
        TRY_TO_DECIMAL(T.PRICE, 18, 2)
        IS DISTINCT FROM
        TRY_TO_DECIMAL(R.PRICE, 18, 2)
    ) AS PRICE_DIFF,

    COUNT_IF(
        TRY_TO_DECIMAL(T.FREIGHT_VALUE, 18, 2)
        IS DISTINCT FROM
