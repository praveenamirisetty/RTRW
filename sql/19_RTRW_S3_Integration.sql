ORDER_PAYMENT_COMPARISON AS (
    SELECT
        O.ORDER_ID,
        O.ORDER_VALUE,
        COALESCE(P.PAYMENT_VALUE, 0) AS PAYMENT_VALUE,
        O.ORDER_VALUE - COALESCE(P.PAYMENT_VALUE, 0)
            AS VARIANCE
    FROM ORDER_TOTALS O
    LEFT JOIN PAYMENT_TOTALS P
        ON O.ORDER_ID = P.ORDER_ID
)

SELECT
    COUNT(*) AS TOTAL_ORDERS,

    COUNT_IF(ABS(VARIANCE) <= 0.01)
        AS MATCHED_ORDERS,

    COUNT_IF(VARIANCE > 0.01)
        AS UNDERPAID_ORDERS,

    COUNT_IF(VARIANCE < -0.01)
        AS OVERPAID_ORDERS,

    SUM(ORDER_VALUE) AS TOTAL_ORDER_VALUE,

    SUM(PAYMENT_VALUE) AS TOTAL_PAYMENT_VALUE,

    SUM(VARIANCE) AS TOTAL_VARIANCE

FROM ORDER_PAYMENT_COMPARISON;

