CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_ORDER_ITEM_TOTALS AS

SELECT
    ORDER_ID,

    SUM(PRODUCT_PRICE) AS PRODUCT_VALUE,

    SUM(FREIGHT_VALUE) AS FREIGHT_VALUE,

    SUM(TOTAL_ITEM_VALUE) AS TOTAL_ITEM_VALUE,

    COUNT(*) AS TOTAL_ITEMS

FROM RTRW_DB.CORE.FACT_ORDER_ITEM

GROUP BY ORDER_ID;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_PAYMENT_TOTALS AS

SELECT
    ORDER_ID,

    SUM(PAYMENT_AMOUNT) AS TOTAL_PAYMENT_VALUE,

    COUNT(*) AS PAYMENT_COUNT

FROM RTRW_DB.CORE.FACT_PAYMENT

GROUP BY ORDER_ID;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_REFUND_TOTALS AS

SELECT
    ORDER_ID,

    SUM(REFUND_AMOUNT) AS TOTAL_COMPLETED_REFUNDS,

    COUNT(*) AS COMPLETED_REFUND_COUNT

FROM RTRW_DB.CORE.FACT_REFUND

WHERE REFUND_STATUS = 'COMPLETED'

GROUP BY ORDER_ID;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_ORDER_RECONCILIATION AS

SELECT
    O.ORDER_ID,

    O.ORDER_STATUS,

    I.PRODUCT_VALUE,

    I.FREIGHT_VALUE,

    I.TOTAL_ITEM_VALUE,

    P.TOTAL_PAYMENT_VALUE,

    R.TOTAL_COMPLETED_REFUNDS,

    COALESCE(I.TOTAL_ITEM_VALUE, 0)
        - COALESCE(P.TOTAL_PAYMENT_VALUE, 0)
        AS PAYMENT_VARIANCE,

    COALESCE(P.TOTAL_PAYMENT_VALUE, 0)
        - COALESCE(R.TOTAL_COMPLETED_REFUNDS, 0)
        AS PAYMENT_AFTER_REFUNDS

FROM RTRW_DB.CORE.FACT_ORDER O

LEFT JOIN RTRW_DB.CORE.VW_ORDER_ITEM_TOTALS I
    ON O.ORDER_ID = I.ORDER_ID

LEFT JOIN RTRW_DB.CORE.VW_PAYMENT_TOTALS P
    ON O.ORDER_ID = P.ORDER_ID

LEFT JOIN RTRW_DB.CORE.VW_REFUND_TOTALS R
    ON O.ORDER_ID = R.ORDER_ID;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_RECONCILIATION_STATUS AS

SELECT
    *,

    CASE

        WHEN PRODUCT_VALUE IS NULL
            THEN 'MISSING_ORDER_ITEMS'

        WHEN TOTAL_PAYMENT_VALUE IS NULL
            THEN 'MISSING_PAYMENT'

        WHEN ABS(PAYMENT_VARIANCE) <= 0.01
            THEN 'MATCHED'

        WHEN PAYMENT_VARIANCE > 0.01
            THEN 'UNDERPAID'

        WHEN PAYMENT_VARIANCE < -0.01
            THEN 'OVERPAID'

        ELSE 'REVIEW_REQUIRED'

    END AS RECONCILIATION_STATUS

FROM RTRW_DB.CORE.VW_ORDER_RECONCILIATION;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_SPLIT_PAYMENT_ANALYSIS AS

SELECT
    ORDER_ID,

    COUNT(*) AS PAYMENT_COUNT,

    SUM(PAYMENT_AMOUNT) AS TOTAL_PAYMENT,

    LISTAGG(
        PAYMENT_TYPE,
        ', '
    ) WITHIN GROUP (
        ORDER BY PAYMENT_SEQUENTIAL
    ) AS PAYMENT_METHODS

FROM RTRW_DB.CORE.FACT_PAYMENT

GROUP BY ORDER_ID

HAVING COUNT(*) > 1;

CREATE OR REPLACE VIEW RTRW_DB.CORE.VW_REFUND_ANOMALIES AS

SELECT
    R.ORDER_ID,

    R.TOTAL_COMPLETED_REFUNDS,

    P.TOTAL_PAYMENT_VALUE,

    R.TOTAL_COMPLETED_REFUNDS
        - P.TOTAL_PAYMENT_VALUE AS EXCESS_REFUND_AMOUNT

FROM RTRW_DB.CORE.VW_REFUND_TOTALS R

JOIN RTRW_DB.CORE.VW_PAYMENT_TOTALS P
    ON R.ORDER_ID = P.ORDER_ID

WHERE R.TOTAL_COMPLETED_REFUNDS >
      P.TOTAL_PAYMENT_VALUE + 0.01;

