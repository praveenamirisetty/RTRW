CREATE OR REPLACE PROCEDURE RTRW_DB.CORE.RUN_RECONCILIATION()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

    CREATE OR REPLACE TEMPORARY TABLE
        RTRW_DB.CORE.TEMP_RECONCILIATION AS

    SELECT *
    FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS;

    RETURN 'Reconciliation analysis completed successfully';

END;
$$;

CALL RTRW_DB.CORE.RUN_RECONCILIATION();

CREATE OR REPLACE TASK RTRW_DB.CORE.RTRW_DAILY_RECON_TASK

WAREHOUSE = RTRW_WH

SCHEDULE = 'USING CRON 0 2 * * * UTC'

AS

CALL RTRW_DB.CORE.RUN_RECONCILIATION();

ALTER TASK RTRW_DB.CORE.RTRW_DAILY_RECON_TASK RESUME;

SHOW TASKS IN SCHEMA RTRW_DB.CORE;