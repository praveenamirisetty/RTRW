-- STEP 4: Inspect reconciliation-related object names
SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    TABLE_TYPE
FROM RTRW_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('CORE', 'ANALYTICS')
  AND (
      TABLE_NAME ILIKE '%RECON%'
      OR TABLE_NAME ILIKE '%ORDER%PAYMENT%'
      OR TABLE_NAME ILIKE '%COMPARISON%'
  )
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- STEP 5: Review completed query history only
SELECT
    QUERY_ID,
    EXECUTION_STATUS,
    TOTAL_ELAPSED_TIME,
    BYTES_SCANNED,
    ROWS_PRODUCED,
    QUERY_TYPE,
    START_TIME
FROM TABLE(
    INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_START => DATEADD('HOUR', -24, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    )
)
WHERE EXECUTION_STATUS IN ('SUCCESS', 'FAILED_WITH_ERROR')
  AND TOTAL_ELAPSED_TIME >= 0
ORDER BY START_TIME DESC;

