SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT_IF(TOTAL_COMPLETED_REFUNDS > 0) AS ORDERS_WITH_COMPLETED_REFUNDS,
    COUNT_IF(TOTAL_COMPLETED_REFUNDS IS NULL) AS NULL_REFUND_VALUES,
    COUNT_IF(TOTAL_COMPLETED_REFUNDS = 0) AS ZERO_REFUND_VALUES
FROM CORE.VW_ORDER_RECONCILIATION;

SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT_IF(PAYMENT_VARIANCE = 0) AS ZERO_VARIANCE_ORDERS,
    COUNT_IF(PAYMENT_VARIANCE <> 0) AS VARIANCE_ORDERS,
    COUNT_IF(PAYMENT_VARIANCE IS NULL) AS NULL_VARIANCE_ORDERS
FROM CORE.VW_ORDER_RECONCILIATION;

SELECT
    COUNT(*) AS TOTAL_REFUND_ANOMALIES,
    COUNT_IF(EXCESS_REFUND_AMOUNT > 0) AS EXCESS_REFUND_CASES
