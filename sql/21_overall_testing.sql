USE DATABASE RTRW_DB;
USE WAREHOUSE RTRW_WH;

-- 1. Source table row counts
SELECT 'ORDERS' AS TABLE_NAME, COUNT(*) AS TOTAL_ROWS
FROM RAW.RAW_ORDERS

UNION ALL

SELECT 'ORDER_ITEMS', COUNT(*)
FROM RAW.RAW_ORDER_ITEMS

UNION ALL

SELECT 'PAYMENTS', COUNT(*)
FROM RAW.RAW_PAYMENTS

UNION ALL

SELECT 'REFUNDS', COUNT(*)
FROM RAW.RAW_REFUNDS;

-- 2. Reconciliation performance
SELECT
    RECONCILIATION_STATUS,
    COUNT(*) AS ORDER_COUNT,
    SUM(COALESCE(ORDER_VALUE, 0)) AS TOTAL_ORDER_VALUE,
    SUM(COALESCE(PAYMENT_VALUE, 0)) AS TOTAL_PAYMENT_VALUE
FROM CORE.ORDER_PAYMENT_COMPARISON
GROUP BY RECONCILIATION_STATUS;

-- 3. Refund aggregation performance
SELECT
    REFUND_STATUS,
    REFUND_TYPE,
    COUNT(*) AS REFUND_COUNT,
    SUM(REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT
FROM RAW.RAW_REFUNDS
GROUP BY REFUND_STATUS, REFUND_TYPE;

-- 4. Recent Snowflake query execution history
SELECT
    QUERY_ID,
    EXECUTION_STATUS,
    TOTAL_ELAPSED_TIME,
    BYTES_SCANNED,
    ROWS_PRODUCED,
    QUERY_TYPE
FROM TABLE(
    INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_START => DATEADD('HOUR', -24, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    )
)
ORDER BY START_TIME DESC;

