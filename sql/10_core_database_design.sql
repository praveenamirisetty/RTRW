USE WAREHOUSE RTRW_WH;

USE DATABASE RTRW_DB;

USE SCHEMA CORE;

CREATE TABLE IF NOT EXISTS CORE.DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER AUTOINCREMENT,
    CUSTOMER_ID VARCHAR(100) NOT NULL,
    CUSTOMER_UNIQUE_ID VARCHAR(100),
    ZIP_CODE_PREFIX VARCHAR(50),
    CUSTOMER_CITY VARCHAR(200),
    CUSTOMER_STATE VARCHAR(20),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.DIM_SELLER (
    SELLER_KEY NUMBER AUTOINCREMENT,
    SELLER_ID VARCHAR(100) NOT NULL,
    ZIP_CODE_PREFIX VARCHAR(50),
    SELLER_CITY VARCHAR(200),
    SELLER_STATE VARCHAR(20),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.DIM_PRODUCT (
    PRODUCT_KEY NUMBER AUTOINCREMENT,
    PRODUCT_ID VARCHAR(100) NOT NULL,
    PRODUCT_CATEGORY_NAME VARCHAR(200),
    PRODUCT_NAME_LENGTH NUMBER,
    PRODUCT_DESCRIPTION_LENGTH NUMBER,
    PRODUCT_PHOTOS_QTY NUMBER,
    PRODUCT_WEIGHT_G NUMBER(18,2),
    PRODUCT_LENGTH_CM NUMBER(18,2),
    PRODUCT_HEIGHT_CM NUMBER(18,2),
    PRODUCT_WIDTH_CM NUMBER(18,2),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.DIM_DATE (
    DATE_KEY NUMBER(8,0),
    FULL_DATE DATE,
    DAY_NUMBER NUMBER,
    DAY_NAME VARCHAR(20),
    MONTH_NUMBER NUMBER,
    MONTH_NAME VARCHAR(20),
    QUARTER_NUMBER NUMBER,
    YEAR_NUMBER NUMBER,
    WEEK_NUMBER NUMBER,
    IS_WEEKEND BOOLEAN
);

CREATE TABLE IF NOT EXISTS CORE.FACT_ORDER (
    ORDER_ID VARCHAR(100) NOT NULL,
    CUSTOMER_ID VARCHAR(100),
    ORDER_STATUS VARCHAR(50),

    ORDER_DATE TIMESTAMP_NTZ,
    APPROVED_DATE TIMESTAMP_NTZ,
    DELIVERED_DATE TIMESTAMP_NTZ,
    ESTIMATED_DELIVERY_DATE TIMESTAMP_NTZ,

    ORDER_DATE_KEY NUMBER(8,0),

    SOURCE_SYSTEM VARCHAR(50) DEFAULT 'OLIST',

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.FACT_ORDER_ITEM (
    ORDER_ID VARCHAR(100) NOT NULL,
    ORDER_ITEM_ID NUMBER(10,0),
    PRODUCT_ID VARCHAR(100),
    SELLER_ID VARCHAR(100),

    SHIPPING_LIMIT_DATE TIMESTAMP_NTZ,

    PRODUCT_PRICE NUMBER(18,2),
    FREIGHT_VALUE NUMBER(18,2),

    TOTAL_ITEM_VALUE NUMBER(18,2),

    SOURCE_SYSTEM VARCHAR(50) DEFAULT 'OLIST',

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.FACT_PAYMENT (
    PAYMENT_ID VARCHAR(200),
    ORDER_ID VARCHAR(100) NOT NULL,

    PAYMENT_SEQUENTIAL NUMBER(10,0),
    PAYMENT_TYPE VARCHAR(50),
    PAYMENT_INSTALLMENTS NUMBER(10,0),

    PAYMENT_AMOUNT NUMBER(18,2),

    CURRENCY VARCHAR(10) DEFAULT 'BRL',

    SOURCE_SYSTEM VARCHAR(50) DEFAULT 'OLIST',

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.FACT_REFUND (
    REFUND_ID VARCHAR(100) NOT NULL,
    ORDER_ID VARCHAR(100) NOT NULL,
    CUSTOMER_ID VARCHAR(100),

    REFUND_DATE TIMESTAMP_NTZ,

    REFUND_AMOUNT NUMBER(18,2),
    RESTOCKING_FEE NUMBER(18,2),
    TAX_REFUNDED NUMBER(18,2),

    REFUND_STATUS VARCHAR(50),
    REFUND_TYPE VARCHAR(50),

    CURRENCY VARCHAR(10),

    DATA_ORIGIN VARCHAR(50)
        DEFAULT 'SYNTHETIC',

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CORE.FACT_RECONCILIATION (
    RECONCILIATION_ID NUMBER AUTOINCREMENT,

    ORDER_ID VARCHAR(100) NOT NULL,

    PRODUCT_VALUE NUMBER(18,2),
    FREIGHT_VALUE NUMBER(18,2),

    TOTAL_ITEM_VALUE NUMBER(18,2),
    TOTAL_PAYMENT_VALUE NUMBER(18,2),

    COMPLETED_REFUND_VALUE NUMBER(18,2),

    PAYMENT_VARIANCE NUMBER(18,2),

    REFUND_VARIANCE NUMBER(18,2),

    RECONCILIATION_STATUS VARCHAR(50),

    RECONCILIATION_RUN_ID NUMBER,

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS AUDIT.RECONCILIATION_RUN (
    RUN_ID NUMBER AUTOINCREMENT,
    RUN_START_TIME TIMESTAMP_NTZ,
    RUN_END_TIME TIMESTAMP_NTZ,
    TOTAL_ORDERS NUMBER,
    MATCHED_ORDERS NUMBER,
    UNMATCHED_ORDERS NUMBER,
    EXCEPTION_COUNT NUMBER,
    RUN_STATUS VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS CORE.EXCEPTION_QUEUE (
    EXCEPTION_ID NUMBER AUTOINCREMENT,

    ORDER_ID VARCHAR(100),

    EXCEPTION_TYPE VARCHAR(100),

    ORDER_AMOUNT NUMBER(18,2),
    PAYMENT_AMOUNT NUMBER(18,2),
    REFUND_AMOUNT NUMBER(18,2),

    VARIANCE_AMOUNT NUMBER(18,2),

    EXCEPTION_STATUS VARCHAR(50)
        DEFAULT 'OPEN',

    PRIORITY VARCHAR(30),

    ASSIGNED_TO VARCHAR(100),

    CREATED_AT TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP(),

    RESOLVED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS AUDIT.EXCEPTION_HISTORY (
    HISTORY_ID NUMBER AUTOINCREMENT,
    EXCEPTION_ID NUMBER,
    ORDER_ID VARCHAR(100),

    OLD_STATUS VARCHAR(50),
    NEW_STATUS VARCHAR(50),

    ACTION_DESCRIPTION VARCHAR(500),

    UPDATED_BY VARCHAR(100),

    UPDATED_AT TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS AUDIT.RECONCILIATION_SNAPSHOT (
    SNAPSHOT_ID NUMBER AUTOINCREMENT,

    RUN_ID NUMBER,

    SNAPSHOT_DATE TIMESTAMP_NTZ,

    TOTAL_ORDERS NUMBER,

    MATCHED_ORDERS NUMBER,

    UNMATCHED_ORDERS NUMBER,

    TOTAL_ORDER_VALUE NUMBER(18,2),

    TOTAL_PAYMENT_VALUE NUMBER(18,2),

    TOTAL_REFUND_VALUE NUMBER(18,2),

    TOTAL_VARIANCE NUMBER(18,2)
);