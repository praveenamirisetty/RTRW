CREATE OR REPLACE VIEW RTRW_DB.ANALYTICS.VW_EXECUTIVE_OVERVIEW AS

SELECT
    COUNT(*) AS TOTAL_ORDERS,

    COUNT_IF(
        RECONCILIATION_STATUS = 'MATCHED'
    ) AS MATCHED_ORDERS,

    COUNT_IF(
        RECONCILIATION_STATUS <> 'MATCHED'
    ) AS UNMATCHED_ORDERS,

    ROUND(
        100.0 *
        COUNT_IF(RECONCILIATION_STATUS = 'MATCHED')
        / NULLIF(COUNT(*), 0),
        2
    ) AS MATCH_RATE_PERCENTAGE,

    SUM(COALESCE(TOTAL_ITEM_VALUE, 0))
        AS TOTAL_ORDER_VALUE,

    SUM(COALESCE(TOTAL_PAYMENT_VALUE, 0))
        AS TOTAL_PAYMENT_VALUE,

    SUM(COALESCE(TOTAL_COMPLETED_REFUNDS, 0))
        AS SYNTHETIC_COMPLETED_REFUNDS,

    SUM(COALESCE(PAYMENT_VARIANCE, 0))
        AS TOTAL_PAYMENT_VARIANCE

FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS;

CREATE OR REPLACE VIEW RTRW_DB.ANALYTICS.VW_PAYMENT_ANALYSIS AS

SELECT
    PAYMENT_TYPE,

    COUNT(*) AS TOTAL_TRANSACTIONS,

    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,

    SUM(PAYMENT_AMOUNT) AS TOTAL_PAYMENT_AMOUNT,

    AVG(PAYMENT_AMOUNT) AS AVERAGE_PAYMENT_AMOUNT

FROM RTRW_DB.CORE.FACT_PAYMENT

GROUP BY PAYMENT_TYPE;

CREATE OR REPLACE VIEW RTRW_DB.ANALYTICS.VW_REFUND_ANALYSIS AS

SELECT
    REFUND_STATUS,

    REFUND_TYPE,

    DATA_ORIGIN,

    CURRENCY,

    COUNT(*) AS TOTAL_REFUNDS,

    SUM(REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT,

    SUM(RESTOCKING_FEE) AS TOTAL_RESTOCKING_FEES,

    SUM(TAX_REFUNDED) AS TOTAL_TAX_REFUNDED

FROM RTRW_DB.CORE.FACT_REFUND

GROUP BY
    REFUND_STATUS,
    REFUND_TYPE,
    DATA_ORIGIN,
    CURRENCY;

CREATE OR REPLACE VIEW RTRW_DB.ANALYTICS.VW_EXCEPTION_ANALYSIS AS

SELECT
    EXCEPTION_TYPE,

    EXCEPTION_STATUS,

    PRIORITY,

    COUNT(*) AS TOTAL_EXCEPTIONS,

    SUM(ABS(VARIANCE_AMOUNT)) AS TOTAL_VARIANCE_AMOUNT,

    AVG(
        DATEDIFF(
            DAY,
            CREATED_AT,
            COALESCE(RESOLVED_AT, CURRENT_TIMESTAMP())
        )
    ) AS AVERAGE_AGING_DAYS

FROM RTRW_DB.CORE.EXCEPTION_QUEUE

GROUP BY
    EXCEPTION_TYPE,
    EXCEPTION_STATUS,
    PRIORITY;

CREATE OR REPLACE VIEW RTRW_DB.ANALYTICS.VW_ORDER_FINANCIAL_ANALYSIS AS

SELECT
    ORDER_ID,

    PRODUCT_VALUE,

    FREIGHT_VALUE,

    TOTAL_ITEM_VALUE,

    TOTAL_PAYMENT_VALUE,

    TOTAL_COMPLETED_REFUNDS,

    PAYMENT_VARIANCE,

    RECONCILIATION_STATUS

FROM RTRW_DB.CORE.VW_RECONCILIATION_STATUS;

SHOW VIEWS IN SCHEMA RTRW_DB.ANALYTICS;

SELECT *
FROM RTRW_DB.ANALYTICS.VW_EXECUTIVE_OVERVIEW;

SELECT *
FROM RTRW_DB.ANALYTICS.VW_PAYMENT_ANALYSIS;

SELECT *
FROM RTRW_DB.ANALYTICS.VW_REFUND_ANALYSIS;

SELECT *
FROM RTRW_DB.ANALYTICS.VW_EXCEPTION_ANALYSIS;

SELECT *
FROM RTRW_DB.ANALYTICS.VW_ORDER_FINANCIAL_ANALYSIS
LIMIT 20;