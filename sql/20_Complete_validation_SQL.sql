
USE DATABASE RTRW_DB;
USE WAREHOUSE COMPUTE_WH;

-- CHECK 1: Source table integrity
SELECT
    'ORDERS' AS DATASET,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ORDER_ID) AS DISTINCT_ORDER_IDS,
    COUNT(*) - COUNT(DISTINCT ORDER_ID) AS DUPLICATE_OR_NULL_KEYS
FROM RTRW_DB.RAW.RAW_ORDERS

UNION ALL

SELECT
    'ORDER_ITEMS',
    COUNT(*),
    COUNT(DISTINCT ORDER_ID),
    COUNT(*) - COUNT(DISTINCT ORDER_ID)
FROM RTRW_DB.RAW.RAW_ORDER_ITEMS

UNION ALL

SELECT
    'PAYMENTS',
    COUNT(*),
    COUNT(DISTINCT ORDER_ID),
    COUNT(*) - COUNT(DISTINCT ORDER_ID)
FROM RTRW_DB.RAW.RAW_PAYMENTS;


-- CHECK 2: Orphan records
SELECT
    'PAYMENTS_WITHOUT_ORDERS' AS CHECK_NAME,
    COUNT(*) AS ISSUE_COUNT
FROM RTRW_DB.RAW.RAW_PAYMENTS P
LEFT JOIN RTRW_DB.RAW.RAW_ORDERS O
    ON P.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL

UNION ALL

SELECT
    'ORDER_ITEMS_WITHOUT_ORDERS',
    COUNT(*)
FROM RTRW_DB.RAW.RAW_ORDER_ITEMS I
LEFT JOIN RTRW_DB.RAW.RAW_ORDERS O
    ON I.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL;


-- CHECK 3: Reconciliation run verification
SELECT
    RUN_ID,
    TOTAL_ORDERS,
    MATCHED_ORDERS,
    UNMATCHED_ORDERS,
    EXCEPTION_COUNT,
    RUN_STATUS,
    MATCHED_ORDERS + UNMATCHED_ORDERS AS RECONCILED_ORDERS,
    TOTAL_ORDERS -
        (MATCHED_ORDERS + UNMATCHED_ORDERS) AS COUNT_DIFFERENCE
FROM RTRW_DB.AUDIT.RECONCILIATION_RUN;


-- CHECK 4: Refund status and type validation
SELECT
    REFUND_STATUS,
    REFUND_TYPE,
    COUNT(*) AS REFUND_COUNT,
    SUM(REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT,
    SUM(RESTOCKING_FEE) AS TOTAL_RESTOCKING_FEE,
    SUM(TAX_REFUNDED) AS TOTAL_TAX_REFUNDED
FROM RTRW_DB.RAW.RAW_REFUNDS
GROUP BY REFUND_STATUS, REFUND_TYPE
ORDER BY REFUND_STATUS, REFUND_TYPE;


-- CHECK 5: Refund snapshot validation
SELECT
    S.SNAPSHOT_ID,
    S.TOTAL_REFUND_VALUE AS SNAPSHOT_REFUND_VALUE,
    R.COMPLETED_REFUND_VALUE,
    S.TOTAL_REFUND_VALUE - R.COMPLETED_REFUND_VALUE
        AS REFUND_VARIANCE,
    CASE
        WHEN ABS(
            S.TOTAL_REFUND_VALUE - R.COMPLETED_REFUND_VALUE
        ) < 0.01
        THEN 'PASS'
        ELSE 'FAIL'
    END AS VALIDATION_STATUS
FROM RTRW_DB.AUDIT.RECONCILIATION_SNAPSHOT S
CROSS JOIN (
    SELECT
        COALESCE(SUM(REFUND_AMOUNT), 0)
            AS COMPLETED_REFUND_VALUE
    FROM RTRW_DB.RAW.RAW_REFUNDS
    WHERE UPPER(REFUND_STATUS) = 'COMPLETED'
) R;


-- CHECK 6: Data quality validation results
SELECT
    CHECK_ID,
    DATASET_NAME,
    CHECK_NAME,
    ISSUE_COUNT,
    STATUS
FROM RTRW_DB.AUDIT.DATA_QUALITY_RESULTS
ORDER BY CHECK_ID;

-- CHECK 1A: Orders - ORDER_ID should be unique
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ORDER_ID) AS DISTINCT_ORDER_IDS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID
            FROM RTRW_DB.RAW.RAW_ORDERS
            WHERE ORDER_ID IS NOT NULL
            GROUP BY ORDER_ID
            HAVING COUNT(*) > 1
        )
    ) AS DUPLICATE_ORDER_IDS
FROM RTRW_DB.RAW.RAW_ORDERS;


-- CHECK 1B: Order items - composite key
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(ORDER_ITEM_ID IS NULL) AS NULL_ITEM_IDS,
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID, ORDER_ITEM_ID
            FROM RTRW_DB.RAW.RAW_ORDER_ITEMS
            WHERE ORDER_ID IS NOT NULL
              AND ORDER_ITEM_ID IS NOT NULL
            GROUP BY ORDER_ID, ORDER_ITEM_ID
            HAVING COUNT(*) > 1
        )
    ) AS DUPLICATE_ITEM_KEYS
FROM RTRW_DB.RAW.RAW_ORDER_ITEMS;


-- CHECK 1C: Payments - composite key
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(PAYMENT_SEQUENTIAL IS NULL) AS NULL_PAYMENT_SEQUENCES,
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID, PAYMENT_SEQUENTIAL
            FROM RTRW_DB.RAW.RAW_PAYMENTS
            WHERE ORDER_ID IS NOT NULL
              AND PAYMENT_SEQUENTIAL IS NOT NULL
            GROUP BY ORDER_ID, PAYMENT_SEQUENTIAL
            HAVING COUNT(*) > 1
        )
    ) AS DUPLICATE_PAYMENT_KEYS
FROM RTRW_DB.RAW.RAW_PAYMENTS;


-- CHECK 6: Correct data quality column name
SELECT
    CHECK_ID,
    DATASET_NAME,
    CHECK_NAME,
    ISSUE_COUNT,
    CHECK_STATUS
FROM RTRW_DB.AUDIT.DATA_QUALITY_RESULTS
ORDER BY CHECK_ID;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(ORDER_ITEM_ID IS NULL) AS NULL_ITEM_IDS,
    (
        SELECT COUNT(*)
        FROM (
            SELECT ORDER_ID, ORDER_ITEM_ID
            FROM RTRW_DB.RAW.RAW_ORDER_ITEMS
            WHERE ORDER_ID IS NOT NULL
              AND ORDER_ITEM_ID IS NOT NULL
            GROUP BY ORDER_ID, ORDER_ITEM_ID
            HAVING COUNT(*) > 1
        )
    ) AS DUPLICATE_ITEM_KEYS
FROM RTRW_DB.RAW.RAW_ORDER_ITEMS;