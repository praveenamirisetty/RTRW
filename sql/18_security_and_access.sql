USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RTRW_ENGINEER_ROLE;

CREATE ROLE IF NOT EXISTS RTRW_FINANCE_ROLE;

CREATE ROLE IF NOT EXISTS RTRW_REPORTING_ROLE;

GRANT USAGE ON DATABASE RTRW_DB
TO ROLE RTRW_REPORTING_ROLE;

GRANT USAGE ON SCHEMA RTRW_DB.ANALYTICS
TO ROLE RTRW_REPORTING_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA RTRW_DB.ANALYTICS
TO ROLE RTRW_REPORTING_ROLE;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA RTRW_DB.ANALYTICS
TO ROLE RTRW_REPORTING_ROLE;